namespace {
class MRISC32AsmPrinter : public AsmPrinter {
  bool lowerOperand(const MachineOperand &MO, MCOperand &MCO);
  MCInst MachineInstrToMCInst(const MachineInstr &MI);

public:
  explicit MRISC32AsmPrinter(TargetMachine &TM,
                           std::unique_ptr<MCStreamer> Streamer)
      : AsmPrinter(TM, std::move(Streamer)) {}

  StringRef getPassName() const override { return "MRISC32 Assembly Printer"; }

  void emitInstruction(const MachineInstr *MI) override;
};
} // end anonymous namespace.

/// Returns true if MO translates to an MCOperand.
/// When false is returned, this means that no MCOperand needs to
/// be produced for this MO (e.g., for an implicit MO.)
bool MRISC32AsmPrinter::lowerOperand(const MachineOperand &MO, MCOperand &MCO) {
  switch (MO.getType()) {
  default:
    llvm_unreachable("unknown operand type");
  case MachineOperand::MO_Register:
    // Ignore all implicit register operands.
    if (MO.isImplicit())
      return false;
    MCO = MCOperand::createReg(MO.getReg());
    break;
  case MachineOperand::MO_RegisterMask:
    // Regmasks are like implicit defs.
    return false;
  case MachineOperand::MO_Immediate:
    MCO = MCOperand::createImm(MO.getImm());
    break;
  case MachineOperand::MO_GlobalAddress: {
    const GlobalValue *GV = MO.getGlobal();
    MCSymbol *Sym = getSymbol(GV);
    const MCExpr *Expr = MCSymbolRefExpr::create(Sym, OutContext);
    MCO = MCOperand::createExpr(Expr);
    break;
  }
  case MachineOperand::MO_ExternalSymbol: {
    MCSymbol *Sym = GetExternalSymbolSymbol(MO.getSymbolName());
    const MCExpr *Expr = MCSymbolRefExpr::create(Sym, OutContext);
    MCO = MCOperand::createExpr(Expr);
    break;
  }
  case MachineOperand::MO_MachineBasicBlock:
  case MachineOperand::MO_MCSymbol:
  case MachineOperand::MO_JumpTableIndex:
  case MachineOperand::MO_ConstantPoolIndex:
  case MachineOperand::MO_BlockAddress:
    llvm_unreachable("not yet implemented");
  }
  return true;
}

/// Translate a MachineInstr to a MCInst.
MCInst MRISC32AsmPrinter::MachineInstrToMCInst(const MachineInstr &MI) {
  MCInst TmpInst;
  TmpInst.setOpcode(MI.getOpcode());

  for (const MachineOperand &MO : MI.operands()) {
    MCOperand MCOp;
    if (lowerOperand(MO, MCOp))
      TmpInst.addOperand(MCOp);
  }
  return TmpInst;
}

void MRISC32AsmPrinter::emitInstruction(const MachineInstr *MI) {
  // This function is autogenerated as part of the InstrInfo TableGen backend.
  //MRISC32_MC::verifyInstructionPredicates(MI->getOpcode(),
   //                                     getSubtargetInfo().getFeatureBits());

  MCInst TmpInst = MachineInstrToMCInst(*MI);
  EmitToStreamer(*OutStreamer, TmpInst);
}

